    Import-Module $PSM1 -Force
}

Describe 'Backward compatibility' {
    It '<Command> still accepts -<Parameter>' -ForEach $PreviousParameters {
        $Resolved = Get-Command $Command -ErrorAction Stop
        if ($Resolved -is [System.Management.Automation.AliasInfo]) {
            $Resolved = $Resolved.ResolvedCommand
        }
        $Match = $Resolved.Parameters.Values | Where-Object { $_.Name -eq $Parameter -or $_.Aliases -contains $Parameter }
        $Match | Should -Not -BeNullOrEmpty -Because "scripts using $Command -$Parameter should keep working"
    }
}
